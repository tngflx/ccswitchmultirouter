import { spawnSync } from "node:child_process";
import {
  chmodSync,
  existsSync,
  lstatSync,
  mkdirSync,
  readFileSync,
  writeFileSync,
} from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const SCRIPT_REPO = fileURLToPath(new URL("../", import.meta.url));

export function parseReleaseHookOptions(args) {
  const options = { synchronous: false, help: false };
  for (const argument of args) {
    if (["--synchronous", "-Synchronous"].includes(argument)) {
      options.synchronous = true;
      continue;
    }
    if (["--help", "-h", "-?"].includes(argument)) {
      options.help = true;
      continue;
    }
    throw new Error(`Unknown release hook option: ${argument}`);
  }
  return options;
}

export function newPostCommitHookContent({ synchronous = false } = {}) {
  const command = `node "$repo_root/scripts/local-release-pipeline.mjs" --reason post-commit >> "$log_file" 2>&1${synchronous ? "" : " &"}`;
  return [
    "#!/bin/sh",
    "# Auto-generated by scripts/install-local-release-hook.mjs.",
    "# Runs the local CCSwitchMulti release pipeline after every successful commit.",
    'repo_root="$(git rev-parse --show-toplevel)"',
    'log_dir="$repo_root/scripts/logs"',
    'mkdir -p "$log_dir"',
    'log_file="$log_dir/post-commit-release.log"',
    'command -v node >/dev/null 2>&1 || { echo "Node.js is required: install Node.js and add node to PATH." >&2; exit 1; }',
    'echo "[$(date \'+%Y-%m-%d %H:%M:%S\')] post-commit release triggered for $(git rev-parse --short HEAD)" >> "$log_file"',
    command,
    "",
  ].join("\n");
}

function assertUnlinkedHookDirectories(directory) {
  let current = path.resolve(directory);
  while (true) {
    let item;
    try {
      item = lstatSync(current);
    } catch (error) {
      if (error.code !== "ENOENT") throw error;
    }
    if (item && (item.isSymbolicLink() || !item.isDirectory()))
      throw new Error(
        "Git hook directories must not traverse a link, junction, or non-directory.",
      );
    const parent = path.dirname(current);
    if (parent === current) break;
    current = parent;
  }
}

export function resolveHooksDirectory(repoRoot, { run = spawnSync } = {}) {
  const repo = path.resolve(repoRoot);
  const invoke = (args) =>
    run("git", ["-C", repo, ...args], {
      cwd: repo,
      encoding: "utf8",
      windowsHide: true,
    });
  const configured = invoke(["config", "--get-all", "core.hooksPath"]);
  if (configured?.error || ![0, 1].includes(configured?.status))
    throw new Error("Cannot safely inspect Git core.hooksPath.");
  // A configured path (including an empty value) is user-owned. Do not hijack
  // a shared hook installation or create a file outside Git's default directory.
  if (configured.status === 0)
    throw new Error(
      "Existing core.hooksPath is preserved; integrate the release command into your hook manually.",
    );
  const result = invoke(["rev-parse", "--git-common-dir"]);
  if (result?.error || result?.status !== 0)
    throw new Error("Cannot resolve the Git common directory.");
  const value = String(result.stdout ?? "").trim();
  if (!value || /[\0\r\n]/u.test(value))
    throw new Error("Git returned an invalid common directory.");
  const hooks = path.join(path.resolve(repo, value), "hooks");
  assertUnlinkedHookDirectories(hooks);
  return hooks;
}

export function installLocalReleaseHook(
  repoRoot = SCRIPT_REPO,
  { synchronous = false, run = spawnSync } = {},
) {
  const hooksDir = resolveHooksDirectory(path.resolve(repoRoot), { run });
  const hookPath = path.join(hooksDir, "post-commit");
  const content = newPostCommitHookContent({ synchronous });
  assertUnlinkedHookDirectories(hooksDir);
  // Never truncate an existing user hook, even if its header happens to match
  // ours. A byte-identical installation is a read-only, idempotent operation.
  let item;
  try {
    item = lstatSync(hookPath);
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }
  if (item) {
    if (item.isSymbolicLink() || !item.isFile())
      throw new Error("Existing post-commit link or non-file is preserved.");
    if (readFileSync(hookPath, "utf8") !== content)
      throw new Error(
        "Existing post-commit hook is preserved; integrate the release command manually.",
      );
    return { hookPath, synchronous, unchanged: true };
  }
  mkdirSync(hooksDir, { recursive: true });
  assertUnlinkedHookDirectories(hooksDir);
  // wx makes a hook created after inspection fail closed instead of being lost.
  writeFileSync(hookPath, content, {
    encoding: "utf8",
    flag: "wx",
    mode: 0o755,
  });
  try {
    chmodSync(hookPath, 0o755);
  } catch {
    /* Windows Git can execute the shebang without Unix mode support. */
  }
  return { hookPath, synchronous, unchanged: false };
}

export function main(args = process.argv.slice(2), dependencies = {}) {
  const options = parseReleaseHookOptions(args);
  if (options.help) {
    console.log(
      "Usage: node scripts/install-local-release-hook.mjs [--synchronous]",
    );
    return;
  }
  const result = installLocalReleaseHook(undefined, {
    synchronous: options.synchronous,
    ...dependencies,
  });
  console.log(`Installed local release post-commit hook: ${result.hookPath}`);
  console.log(
    result.synchronous
      ? "Mode: synchronous. git commit waits until packaging finishes."
      : "Mode: background. git commit returns immediately; logs go to scripts/logs/post-commit-release.log.",
  );
  return result;
}

if (
  process.argv[1] &&
  pathToFileURL(path.resolve(process.argv[1])).href === import.meta.url
) {
  try {
    main();
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
